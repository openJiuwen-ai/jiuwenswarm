"""Explicit parent-environment boundary for sandbox runners and commands."""

import json
import os
import re
import sys

ENV_ALLOWLIST = "JIUWENBOX_ENV_ALLOWLIST"
_SERVICE_DECLARATION_KEYS = frozenset({
    "JIUWENBOX_SERVICE_READ_ROOTS", "JIUWENBOX_TOOL_PATHS", "JIUWENBOX_PATH_ALLOWLIST", ENV_ALLOWLIST,
})
_SYSTEM_KEYS = frozenset({
    "PATH", "PATHEXT", "SystemRoot", "windir", "COMSPEC", "SystemDrive",
    "LANG", "LC_ALL", "LC_CTYPE", "PYTHONIOENCODING", "PYTHONUTF8",
})
_LOADER_KEYS = frozenset({
    "LD_PRELOAD", "LD_LIBRARY_PATH", "DYLD_INSERT_LIBRARIES", "DYLD_LIBRARY_PATH",
    "PYTHONPATH", "PYTHONHOME", "PYTHONSTARTUP", "PYTHONSAFEPATH", "PYTHONPYCACHEPREFIX",
    "NODE_OPTIONS", "NODE_PATH", "NODE_EXTRA_CA_CERTS",
})
_WINDOWS_PROFILE_KEYS = frozenset({
    "USERPROFILE", "HOME", "LOCALAPPDATA", "APPDATA", "TEMP", "TMP", "TMPDIR",
})


def strip_service_declarations(env: dict[str, str]) -> None:
    """ACL/inheritance declarations are service inputs, never command settings.

    Keep execution protocol keys such as INJECT_ENV and host soft-delete
    settings intact; filtering all JIUWENBOX_* keys would break those channels.
    """
    for key in list(env):
        if key.upper() in _SERVICE_DECLARATION_KEYS:
            del env[key]


def inherited_environment(*, for_runner: bool = False) -> dict[str, str]:
    """Copy system keys and configured tool keys, preserving empty values.

    Service loader paths and JIUWENBOX_* control settings are runner-only.
    Commands may use loader settings only when explicitly supplied in the
    request/policy, never by inheriting a service's interpreter environment.
    """
    try:
        names = json.loads((os.environ.get(ENV_ALLOWLIST) or "").strip() or "[]")
    except (ValueError, TypeError) as exc:
        raise ValueError("Invalid JIUWENBOX_ENV_ALLOWLIST") from exc
    if not isinstance(names, list) or any(
        not isinstance(name, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name)
        for name in names
    ):
        raise ValueError("JIUWENBOX_ENV_ALLOWLIST must contain exact variable names")
    allowed = _SYSTEM_KEYS | set(names)
    if for_runner:
        allowed |= {"PYTHONPATH", "PYTHONHOME"}
    else:
        allowed = {key for key in allowed if key.upper() not in _LOADER_KEYS}
    if sys.platform == "win32":
        # Profile/temp paths are generated by the sandbox, even if listed.
        allowed = {key for key in allowed if key.upper() not in _WINDOWS_PROFILE_KEYS}
    key_names = {
        key.upper() if sys.platform == "win32" else key: key for key in allowed
    }
    if sys.platform == "win32":
        key_names.update({key.upper(): key for key in _SYSTEM_KEYS})
    inherited = {}
    for key, value in os.environ.items():
        lookup_key = key.upper() if sys.platform == "win32" else key
        if lookup_key == "JIUWENBOX_SOFT_DELETE_PATCH_ONLY":
            continue
        if lookup_key in key_names or (for_runner and lookup_key.startswith("JIUWENBOX_")):
            inherited[key_names.get(lookup_key, key)] = value
    return inherited
