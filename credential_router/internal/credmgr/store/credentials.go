// Credential represents a row in the credentials table.
type Credential struct {
	ID           int64
	UserID       string
	APIBase      string
	KeyTag       string
	ProxyKey     string
	APIKeyCipher []byte
	AuthType     string
	RowVersion   int64
	KekVersion   int64
	DekVersion   int64
	CreatedAt    int64
	UpdatedAt    int64
}

// GenerateProxyKey returns a fresh, collision-resistant proxy lookup key:
// the literal prefix "cr_pk_" followed by 32 bytes of crypto/rand entropy
// encoded as unpadded base64url (43 chars). Uniqueness is enforced by the
// UNIQUE index idx_credentials_proxy_key; a collision (probability ~2^-256)
// is surfaced as platform.ErrConflict on the proxy_key column, which callers
// can detect with IsUniquenessConstraintFor and retry with a fresh key.
func GenerateProxyKey() string {
	var buf [32]byte
	if _, err := rand.Read(buf[:]); err != nil {
		// crypto/rand.Read is documented as never failing on supported
		// platforms; if it does, the process cannot mint safe keys.
		panic(fmt.Sprintf("store: GenerateProxyKey: crypto/rand failed: %v", err))
	}
	return "cr_pk_" + base64.RawURLEncoding.EncodeToString(buf[:])
}

// InsertCredential inserts a new credential. row_version defaults to 1.
// If c.ProxyKey is empty a fresh one is generated by GenerateProxyKey before
// the INSERT, so c.ProxyKey is always populated on return.
// Returns platform.ErrConflict on UNIQUE (user_id, api_base, key_tag) or
// UNIQUE (proxy_key) violation.
func (s *Store) InsertCredential(ctx context.Context, c *Credential) error {
	if c == nil {
		return fmt.Errorf("store: nil credential")
	}
	now := time.Now().Unix()
	c.CreatedAt = now
	c.UpdatedAt = now
	c.RowVersion = 1
	if c.KekVersion == 0 {
		c.KekVersion = 1
	}
	if c.DekVersion == 0 {
		c.DekVersion = 1
	}
	if c.ProxyKey == "" {
		c.ProxyKey = GenerateProxyKey()
	}
	res, err := s.adminDB.ExecContext(ctx,
		`INSERT INTO credentials
			(user_id, api_base, key_tag, proxy_key, api_key_cipher, auth_type,
			 row_version, kek_version, dek_version, created_at, updated_at)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		c.UserID, c.APIBase, c.KeyTag, c.ProxyKey, c.APIKeyCipher, c.AuthType,
		c.RowVersion, c.KekVersion, c.DekVersion, c.CreatedAt, c.UpdatedAt,
	)
	if err != nil {
		if IsUniquenessConstraintFor(err, "proxy_key") {
			// Collision on the generated key: transient and self-healing —
			// callers may retry (InsertCredential regenerates when ProxyKey
			// is empty). Still reported as a conflict, not a hard error.
			return fmt.Errorf("%w: proxy_key collision", platform.ErrConflict)
		}
		if isUniquenessConstraintError(err) {
			return fmt.Errorf("%w: user_id=%q api_base=%q key_tag=%q",
				platform.ErrConflict, c.UserID, c.APIBase, c.KeyTag)
		}
		return fmt.Errorf("store: insert credential: %w", err)
	}
	id, err := res.LastInsertId()
	if err != nil {
		return fmt.Errorf("store: last insert id: %w", err)
	}
	c.ID = id
	return nil
}

// GetCredentialByUserURLTag returns the credential matching the unique key.
// Returns platform.ErrNotFound if no row exists.
func (s *Store) GetCredentialByUserURLTag(ctx context.Context, userID, apiBase, keyTag string) (*Credential, error) {
	row := s.proxyDB.QueryRowContext(ctx,
		`SELECT id, user_id, api_base, key_tag, proxy_key, api_key_cipher, auth_type,
		        row_version, kek_version, dek_version, created_at, updated_at
		 FROM credentials
		 WHERE user_id = ? AND api_base = ? AND key_tag = ?`,
		userID, apiBase, keyTag,
	)
	c := &Credential{}
	err := row.Scan(
		&c.ID, &c.UserID, &c.APIBase, &c.KeyTag, &c.ProxyKey, &c.APIKeyCipher, &c.AuthType,
		&c.RowVersion, &c.KekVersion, &c.DekVersion, &c.CreatedAt, &c.UpdatedAt,
	)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, fmt.Errorf("%w: user_id=%q api_base=%q key_tag=%q",
				platform.ErrNotFound, userID, apiBase, keyTag)
		}
		return nil, fmt.Errorf("store: get credential: %w", err)
	}
	return c, nil
}

