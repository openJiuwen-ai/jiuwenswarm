// ListCredentials returns all credentials, ordered by id, with optional limit/offset.
func (s *Store) ListCredentials(ctx context.Context, limit, offset int) ([]*Credential, error) {
	if limit < 0 {
		return nil, fmt.Errorf("store: limit must be >= 0, got %d", limit)
	}
	if offset < 0 {
		return nil, fmt.Errorf("store: offset must be >= 0, got %d", offset)
	}
	q := `SELECT id, user_id, api_base, key_tag, proxy_key, api_key_cipher, auth_type,
	             row_version, kek_version, dek_version, created_at, updated_at
	      FROM credentials
	      ORDER BY id`
	var args []any
	if limit > 0 {
		q += ` LIMIT ?`
		args = append(args, limit)
		if offset > 0 {
			q += ` OFFSET ?`
			args = append(args, offset)
		}
	} else if offset > 0 {
		q += ` LIMIT -1 OFFSET ?`
		args = append(args, offset)
	}
	rows, err := s.proxyDB.QueryContext(ctx, q, args...)
	if err != nil {
		return nil, fmt.Errorf("store: list credentials: %w", err)
	}
	defer rows.Close()
	var out []*Credential
	for rows.Next() {
		c := &Credential{}
		if err := rows.Scan(
			&c.ID, &c.UserID, &c.APIBase, &c.KeyTag, &c.ProxyKey, &c.APIKeyCipher, &c.AuthType,
			&c.RowVersion, &c.KekVersion, &c.DekVersion, &c.CreatedAt, &c.UpdatedAt,
		); err != nil {
			return nil, fmt.Errorf("store: scan credential: %w", err)
		}
		out = append(out, c)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("store: rows: %w", err)
	}
	return out, nil
}

// UpdateCredential updates api_key_cipher and/or auth_type with optimistic
// row_version lock. Caller signals "keep existing" per field by passing the
// zero value:
//
//	c.APIKeyCipher == nil → keep existing api_key_cipher
//	c.AuthType == ""     → keep existing auth_type
//
// c.KekVersion and c.DekVersion are ALWAYS overwritten (they reflect the
// encryption metadata of whatever cipher was just written; the caller MUST
// pass the snap's versions so Phase A can correctly identify rows that need
// re-encryption). row_version and updated_at are always managed here.
// On success it increments c.RowVersion and sets c.UpdatedAt and c.ID.
// Returns platform.ErrConflict if row_version doesn't match.
// Returns platform.ErrNotFound if id doesn't exist.
func (s *Store) UpdateCredential(ctx context.Context, id int64, c *Credential) error {
	if c == nil {
		return fmt.Errorf("store: nil credential")
	}
	if c.KekVersion == 0 {
		c.KekVersion = 1
	}
	if c.DekVersion == 0 {
		c.DekVersion = 1
	}
	now := time.Now().Unix()
	res, err := s.adminDB.ExecContext(ctx,
		`UPDATE credentials
		 SET api_key_cipher=COALESCE(?, api_key_cipher),
		     auth_type=COALESCE(NULLIF(?, ''), auth_type),
		     kek_version=?,
		     dek_version=?,
		     row_version=row_version+1,
		     updated_at=?
		 WHERE id=? AND row_version=?`,
		c.APIKeyCipher, c.AuthType, c.KekVersion, c.DekVersion, now, id, c.RowVersion,
	)
	if err != nil {
		return fmt.Errorf("store: update credential: %w", err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return fmt.Errorf("store: rows affected: %w", err)
	}
	if n == 0 {
		// Distinguish: row missing or row_version mismatch
		var existing int64
		err := s.adminDB.QueryRowContext(ctx,
			`SELECT row_version FROM credentials WHERE id=?`, id,
		).Scan(&existing)
		if err != nil {
			if errors.Is(err, sql.ErrNoRows) {
				return fmt.Errorf("%w: id=%d", platform.ErrNotFound, id)
			}
			return fmt.Errorf("store: lookup after failed update: %w", err)
		}
		return fmt.Errorf("%w: id=%d expected row_version=%d got=%d",
			platform.ErrConflict, id, c.RowVersion, existing)
	}
	c.RowVersion++
	c.UpdatedAt = now
	c.ID = id
	return nil
}

// DeleteCredential deletes a credential by id with optimistic row_version lock.
// Returns platform.ErrConflict if row_version doesn't match (row gone or version mismatch).
func (s *Store) DeleteCredential(ctx context.Context, id int64, expectedRowVersion int64) error {
	res, err := s.adminDB.ExecContext(ctx,
		`DELETE FROM credentials WHERE id=? AND row_version=?`,
		id, expectedRowVersion,
	)
	if err != nil {
		return fmt.Errorf("store: delete credential: %w", err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return fmt.Errorf("store: rows affected: %w", err)
	}
	if n == 0 {
		return fmt.Errorf("%w: id=%d", platform.ErrConflict, id)
	}
	return nil
}

// CountStragglersByDekVersion reports Phase A progress for the keystore status
// endpoint. Counts rows whose dek_version is below targetDek.
func (s *Store) CountStragglersByDekVersion(ctx context.Context, targetDek int64) (int64, error) {
	var n int64
	err := s.adminDB.QueryRowContext(ctx, "SELECT COUNT(*) FROM credentials WHERE dek_version < ?", targetDek).Scan(&n)
	if err != nil {
		return 0, fmt.Errorf("count stragglers: %w", err)
	}
	return n, nil
}

// isUniquenessConstraintError detects SQLite UNIQUE (2067) or PRIMARY KEY
// (1555) violations via the extended code; both are mappable to platform.ErrConflict.
func isUniquenessConstraintError(err error) bool {
	var sqliteErr sqlite3.Error
	if errors.As(err, &sqliteErr) {
		return sqliteErr.ExtendedCode == sqlite3.ErrConstraintUnique ||
			sqliteErr.ExtendedCode == sqlite3.ErrConstraintPrimaryKey
	}
	return false
}

// IsUniquenessConstraintFor reports whether err is a UNIQUE/PRIMARY KEY
// constraint violation affecting the named column. The credentials table now
// has two uniqueness dimensions — (user_id, api_base, key_tag) and proxy_key —
// and callers need to tell them apart: a proxy_key collision comes from the
// auto-generated key and is transient (retry with a fresh GenerateProxyKey),
// while a user_id/api_base/key_tag collision is a genuine duplicate.
func IsUniquenessConstraintFor(err error, column string) bool {
	if !isUniquenessConstraintError(err) {
		return false
	}
	var sqliteErr sqlite3.Error
	if errors.As(err, &sqliteErr) {
		return strings.Contains(sqliteErr.Error(), column)
	}
	return false
}
