class _RangeTable:
    """Constant code-point range table with bisect-based membership."""

    __slots__ = ("_ranges", "_starts")

    def __init__(self, ranges: tuple[tuple[int, int], ...]) -> None:
        self._ranges = ranges
        self._starts = tuple(start for start, _end in ranges)

    def __contains__(self, code_point: int) -> bool:
        index = bisect_right(self._starts, code_point) - 1
        return index >= 0 and self._ranges[index][0] <= code_point <= self._ranges[index][1]


