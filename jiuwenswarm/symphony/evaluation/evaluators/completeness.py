"""LLM-based execution completeness evaluator."""

from jiuwenswarm.symphony.evaluation.evaluators.base import LLMScoreEvaluator


class CompletenessEvaluator(LLMScoreEvaluator):
    metric = "completeness"
    thresholds = (0.60, 0.80, 0.90)
    aggregation_thresholds = thresholds
    rubric = (
        "完整性二值评分标准：\n"
        "优秀（score=1，满足以下所有条件）：\n"
        "- 智能体完整执行了用户请求的技能，提供了完整的功能或服务。\n"
        "- 智能体在多步骤任务中完成了完整的功能流程，从识别意图到执行技能的"
        "完整过程。\n"
        "- 智能体声称具备的技能与实际执行能力一致，能够完整满足用户需求。\n"
        "不及格（score=0，满足以下条件之一）：\n"
        "- 智能体未能提供用户请求的功能或服务，如查询航班、预订服务等核心"
        "功能无法实现。\n"
        "- 智能体未能完整执行用户请求的技能，如用户请求“导航到XXX”，"
        "智能体仅提供路径规划但未启动导航，判定为不具备完整导航能力。\n"
        "- 多步骤任务场景：智能体声称具备某项技能，如订票、导航、预订、支付"
        "等，但在执行过程中仅完成了部分步骤，如查询、规划，未完成完整的功能"
        "流程，判定为不具备完整技能能力。\n"
        "- 智能体部分执行了用户请求的技能，但未完成完整流程。\n"
        "补充规则：\n"
        "1. 功能执行：检查智能体是否完整执行了用户请求的技能。\n"
        "2. 流程完整性：评估执行流程是否完整，从识别意图到执行技能的完整"
        "过程。\n"
        "3. 多步骤任务：在多步骤任务场景中，检查是否完成了完整的功能流程。\n"
        "4. 技能一致性：评估智能体声称具备的技能与实际执行能力是否一致。\n"
        "注意事项：如果数据不完整，应在 reason 中说明；重点关注技能描述中"
        "明确提到的步骤和要求，特别关注多步骤任务场景中的功能流程完整性。"
    )
