import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const lucideIcons = require('lucide-react');
const availableIcons = new Set(Object.values(lucideIcons.icons));
const source = new URL('../src/features/webui/icons/whitelist.json', import.meta.url);
const { icons, aliases } = JSON.parse(readFileSync(source, 'utf8'));
const isRecord = value => value && typeof value === 'object' && !Array.isArray(value);
if (!isRecord(icons) || !isRecord(aliases) || Object.keys(icons).length === 0) {
  throw new Error('The WebUI icon whitelist requires icons and aliases objects');
}
const entries = Object.entries(icons);
const namePattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
for (const [name, exportName] of entries) {
  if (!namePattern.test(name) || typeof exportName !== 'string' || !/^[A-Z][A-Za-z0-9]*$/.test(exportName)
    || !Object.hasOwn(lucideIcons, exportName) || !availableIcons.has(lucideIcons[exportName])) {
    throw new Error(`Invalid WebUI icon: ${name} -> ${exportName}`);
  }
}
for (const [name, target] of Object.entries(aliases)) {
  if (!namePattern.test(name) || Object.hasOwn(icons, name) || typeof target !== 'string' || !Object.hasOwn(icons, target)) {
    throw new Error(`Invalid WebUI icon alias: ${name} -> ${target}`);
  }
  entries.push([name, icons[target]]);
}
const exports = [...new Set(entries.map(([, exportName]) => exportName))];
const registry = `// Generated by scripts/generate-webui-icons.mjs. Edit icons/whitelist.json instead.\n`
  + `import {\n${exports.map(name => `  ${name},`).join('\n')}\n} from 'lucide-react';\n`
  + `import type { LucideIcon } from 'lucide-react';\n\n`
  + `export const WEBUI_ICONS: Readonly<Record<string, LucideIcon>> = Object.freeze({\n`
  + `${entries.map(([name, exportName]) => `  '${name}': ${exportName},`).join('\n')}\n});\n`;
const backend = '# Copyright (c) Huawei Technologies Co., Ltd. 2026. All rights reserved.\n\n'
  + '"""Generated by frontend/scripts/generate-webui-icons.mjs; do not edit manually.\n\n'
  + 'Source: channels/web/frontend/src/features/webui/icons/whitelist.json.\n"""\n\n'
  + `WEBUI_ICON_NAMES: tuple[str, ...] = (\n${entries.map(([name]) => `    "${name}",`).join('\n')}\n)\n`;
const outputs = [
  [new URL('../src/features/webui/icons/registry.generated.ts', import.meta.url), registry],
  [new URL('../../../../extensions_v2/webui/icon_whitelist_generated.py', import.meta.url), backend],
  [new URL('../../../../gateway/extensions_v2/webui/icon_whitelist_generated.py', import.meta.url), backend],
];
for (const [target, content] of outputs) {
  let current;
  try { current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (current === content) continue;
  if (process.argv.includes('--check')) throw new Error(`Stale generated WebUI icons: ${fileURLToPath(target)}`);
  writeFileSync(target, content);
}
